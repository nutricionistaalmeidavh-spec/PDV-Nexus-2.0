/** P2 browser QA: real SQLite, Chromium, admin UI, stock deduction and public menu. Never deploy. */
import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';import os from 'node:os';import path from 'node:path';
import {createApp} from '../apps/server/src/server.mjs';
const folder=fs.mkdtempSync(path.join(os.tmpdir(),'nexus-p2-e2e-'));
const screenshots=path.resolve('artifacts/qa');fs.mkdirSync(screenshots,{recursive:true});
const app=createApp({dataPath:path.join(folder,'qa.db')});
const origin=await app.listen({port:0});let browser,page;
const snap=async name=>{if(page&&!page.isClosed())await page.screenshot({path:path.join(screenshots,name+'.png'),fullPage:true}).catch(()=>{});};
try{
 browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const context=await browser.newContext({viewport:{width:1440,height:900},acceptDownloads:true,locale:'pt-BR'});
 page=await context.newPage();await page.goto(origin);
 await page.locator('#operator-login-form input[name=username]').fill('admin');
 await page.locator('#operator-login-form input[name=password]').fill('senhaMuitoForte-2026');
 await page.locator('#operator-login-form button').click();
 await page.locator('#operator-login-form').waitFor({state:'detached'});
 await page.locator('[data-view="products"]').click();
 await page.locator('#product-form input[name=name]').fill('X-P2-QA');
 await page.locator('#product-form input[name=price]').fill('24.00');
 await page.locator('#product-form button[type=submit]').click();
 await page.locator('#product-list').getByText('X-P2-QA').waitFor();
 await page.locator('[data-view="stock"]').click();
 await page.locator('#stock-ingredient-form input[name=name]').fill('Carne QA');
 await page.locator('#stock-ingredient-form input[name=lowStock]').fill('100');
 await page.locator('#stock-ingredient-form button').click();
 await page.locator('#stock-ingredient-list').getByText('Carne QA').waitFor();
 await page.locator('#stock-receive-ingredient').selectOption({label:'Carne QA (g)'});
 await page.locator('#stock-receive-form input[name=quantity]').fill('2000');
 await page.locator('#stock-receive-form input[name=cost]').fill('50.00');
 await page.locator('#stock-receive-form button').click();
 await page.waitForFunction(()=>document.querySelector('#stock-summary')?.textContent.includes('50,00'));
 await page.locator('#stock-recipe-product').selectOption({label:'X-P2-QA'});
 await page.locator('#stock-recipe-ingredient').selectOption({label:'Carne QA (g)'});
 await page.locator('#stock-recipe-quantity').fill('200');
 await page.locator('#stock-recipe-add').click();
 await page.locator('#stock-recipe-lines').getByText('Carne QA').waitFor();
 await page.locator('#stock-recipe-save').click();
 await page.waitForFunction(()=>document.querySelector('#toast')?.textContent.includes('Ficha técnica salva'));
 await snap('08-p2-estoque-e-ficha');
 await page.locator('[data-view="cash"]').click();
 await page.locator('#cash-open-form button').click();
 await page.waitForFunction(()=>document.querySelector('#cash-summary')?.textContent.includes('aberto'));
 await page.locator('[data-view="pos"]').click();
 await page.locator('#product-grid button').filter({hasText:'X-P2-QA'}).click();
 await page.waitForFunction(()=>document.querySelector('#cart-total')?.textContent.includes('24,00'));
 await page.locator('#confirm-order').click();
 await page.waitForFunction(()=>document.querySelector('#pay-order')?.disabled===false);
 await page.locator('#pay-order').click();
 await page.locator('#payment-dialog').waitFor({state:'visible'});
 await page.locator('#payment-form button[type=submit]').click();
 await page.waitForFunction(()=>document.querySelector('#order-status')?.textContent==='Fechado');
 const stockAfter=await page.evaluate(async()=>{const r=await fetch('/api/stock/ingredients');return r.json();});
 assert.equal(stockAfter.ingredients.find(x=>x.name==='Carne QA').onHandMilli,1800000);
 await page.locator('[data-view="stock"]').click();
 await page.waitForFunction(()=>document.querySelector('#stock-margin')?.textContent.includes('19,00'));
 await snap('09-p2-margem-estoque-baixado');
 await page.locator('[data-view="delivery"]').click();
 await page.locator('#public-menu-enabled').check();
 await page.locator('#delivery-setting-form button').click();
 await page.waitForFunction(async()=>{const r=await fetch('/api/public/menu');return r.ok;});
 await snap('10-p2-delivery-painel');
 const guestContext=await browser.newContext({viewport:{width:420,height:850},locale:'pt-BR'}),guest=await guestContext.newPage();
 await guest.goto(origin+'/menu.html');
 await guest.locator('#menu-items').getByText('X-P2-QA').waitFor();
 await guest.locator('.menu-card').filter({hasText:'X-P2-QA'}).getByRole('button',{name:'Adicionar'}).click();
 await guest.locator('#menu-checkout input[name=customerName]').fill('Cliente Exemplo QA');
 await guest.locator('#menu-checkout input[name=phone]').fill('16999998888');
 await guest.locator('#menu-checkout input[name=address]').fill('Rua de Teste 400, Centro');
 await guest.locator('#send-request').click();
 await guest.locator('#menu-alert').getByText('Solicitação registrada',{exact:false}).waitFor();
 await guest.screenshot({path:path.join(screenshots,'11-p2-cardapio-digital.png'),fullPage:true});
 await page.locator('#delivery-refresh').click();
 await page.locator('#delivery-request-list').getByText('Cliente Exemplo QA',{exact:false}).waitFor();
 await snap('12-p2-solicitacao-pendente');
 await page.locator('#delivery-request-list').getByRole('button',{name:'Aceitar'}).click();
 await page.waitForFunction(()=>document.querySelector('#toast')?.textContent.includes('Pedido'));
 const deliveries=await page.evaluate(async()=>{const r=await fetch('/api/delivery/requests');return r.json();});
 assert.equal(deliveries.requests[0].status,'ACCEPTED');
 await snap('13-p2-delivery-aceito');
 await guestContext.close();
 console.log('P2 browser E2E PASS: stock, recipe, sale-cost, margin, opt-in public menu, guest request, admin approval');
}catch(error){await snap('erro-p2-qa');console.error('P2 browser QA failed:',error);process.exitCode=1;
}finally{if(browser)await browser.close();await app.close();fs.rmSync(folder,{recursive:true,force:true});}
